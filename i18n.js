export const catalogs = Object.freeze({ en: Object.freeze(en), 'zh-CN': Object.freeze(zhCN) });

export const normalizeLocale = (value) => {
  if (value === 'zh' || value === 'zh-CN') return 'zh-CN';
  return value === 'en' ? 'en' : DEFAULT_LOCALE;
};

export const readStoredLocale = (storage) => {
  try {
    return normalizeLocale(storage?.getItem(STORAGE_KEY));
  } catch {
    return DEFAULT_LOCALE;
  }
};

export const writeStoredLocale = (storage, locale) => {
  try {
    storage?.setItem(STORAGE_KEY, normalizeLocale(locale));
    return true;
  } catch {
    return false;
  }
};

export const translate = (locale, key, params = {}) => {
  const normalized = normalizeLocale(locale);
  const template = catalogs[normalized][key] ?? catalogs.en[key] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(params[name] ?? `{${name}}`));
};

export const applyTranslations = (document, locale) => {
  if (!document) return;
  const normalized = normalizeLocale(locale);
  document.documentElement.lang = normalized;
  document.title = translate(normalized, 'meta.title');
  document.querySelector('meta[name="description"]')
    ?.setAttribute('content', translate(normalized, 'meta.description'));
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    let params = {};
    try { params = JSON.parse(node.getAttribute('data-i18n-params') || '{}'); } catch { params = {}; }
    node.textContent = translate(normalized, node.dataset.i18n, params);
  });
  for (const attribute of ['aria-label', 'alt', 'title', 'data-label']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => {
      node.setAttribute(attribute, translate(normalized, node.getAttribute(`data-i18n-${attribute}`)));
    });
  }
  document.querySelectorAll('[data-locale]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.locale === normalized));
  });
};

export const createLocaleController = ({ document, storage, apply = applyTranslations }) => {
  let currentLocale = readStoredLocale(storage);
  const listeners = new Set();
  const applyCurrent = () => apply(document, currentLocale);
  applyCurrent();
  return {
    getLocale: () => currentLocale,
    t: (key, params) => translate(currentLocale, key, params),
    apply: applyCurrent,
    subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    setLocale(nextLocale) {
      const normalized = normalizeLocale(nextLocale);
      if (normalized === currentLocale) return false;
      currentLocale = normalized;
      writeStoredLocale(storage, currentLocale);
      applyCurrent();
      listeners.forEach((listener) => listener(currentLocale));
      return true;
    },
  };
};
